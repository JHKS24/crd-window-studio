#!/usr/bin/env python3
"""Validate canonical UI catalogs and embed their exact JSON in the native agent."""
from __future__ import annotations
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
# Literal %% consumes no argument. Positional translation may reorder arguments;
# unnumbered translation must preserve their original argument order and types.
PRINTF = re.compile(
    r"%(?:%|(?:(?P<position>[0-9]+)\$)?[-+ #0']*"
    r"(?P<width>\*(?:[0-9]+\$)?|[0-9]*)"
    r"(?:\.(?P<precision>\*(?:[0-9]+\$)?|[0-9]*))?"
    r"(?P<length>hh|ll|[hljztL])?(?P<conversion>[@diouxXfFeEgGaAcCsSpn]))"
)


# --- Catalog and format validation ---

def unique_object(pairs):
    """Build a catalog object while rejecting duplicate keys."""
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate catalog key: {key!r}")
        result[key] = value
    return result


def read_catalog(path: Path) -> dict[str, str]:
    """Load a nonempty catalog and require nonblank string keys and translations."""
    catalog = json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=unique_object,
                         parse_constant=lambda value: (_ for _ in ()).throw(ValueError(value)))
    if not isinstance(catalog, dict) or not catalog:
        raise ValueError(f"{path.name} must contain a nonempty string dictionary")
    for key, value in catalog.items():
        if not isinstance(key, str) or not key.strip() or not isinstance(value, str) or not value.strip():
            raise ValueError(f"{path.name} contains an empty or non-string catalog entry")
    return catalog


def placeholders(text: str) -> Counter:
    """Count printf arguments by position and type, including dynamic width and precision."""
    result = Counter()
    next_position = 1
    modes = set()

    def consume(position, kind):
        """Record one argument and track whether positions are implicit or explicit."""
        nonlocal next_position
        if position is None:
            modes.add("implicit")
            index = next_position
            next_position += 1
        else:
            modes.add("explicit")
            index = int(position)
            if index < 1:
                raise ValueError("printf argument positions must be positive")
        result[(index, kind)] += 1

    for match in PRINTF.finditer(text):
        if match.group(0) == "%%":
            continue
        for field in ("width", "precision"):
            value = match.group(field)
            if value and value.startswith("*"):
                consume(value[1:-1] if value.endswith("$") else None, "d")
        conversion = match.group("conversion")
        conversion = "d" if conversion == "i" else conversion
        consume(match.group("position"), (match.group("length") or "") + conversion)
    if len(modes) > 1:
        raise ValueError("mixed positional and unnumbered printf arguments")
    return result


def checked_catalogs(directory: Path) -> dict[str, dict[str, str]]:
    """Require matching Korean and English keys, source text and printf argument contracts."""
    catalogs = {language: read_catalog(directory / f"{language}.json") for language in ("ko", "en")}
    ko, en = catalogs["ko"], catalogs["en"]
    if ko.keys() != en.keys():
        missing = sorted(ko.keys() - en.keys())
        extra = sorted(en.keys() - ko.keys())
        raise ValueError(f"catalog key sets differ: en missing={missing!r}; en extra={extra!r}")
    for key in ko:
        if ko[key] != key:
            raise ValueError(f"ko identity catalog must preserve its source key: {key!r}")
        source = placeholders(key)
        if placeholders(en[key]) != source:
            raise ValueError(f"printf argument count/type/order mismatch: {key!r}")
    return catalogs


# --- Deterministic native header generation ---

def make_header(catalogs: dict[str, dict[str, str]]) -> tuple[bytes, str]:
    """Encode deterministic catalog JSON and its hash in an escaped C string header."""
    raw = json.dumps(catalogs, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False)
    digest = hashlib.sha256(raw.encode("utf-8")).hexdigest()
    # A normally escaped C string, rather than a raw-string delimiter, safely
    # handles quotes, backslashes, newlines and arbitrary translated body text.
    literal = json.dumps(raw, ensure_ascii=False)
    header = ("// Generated by scripts/generate_localizations.py; edit Localization/{ko,en}.json instead.\n"
              "#pragma once\n"
              f'static const char kCRDLocalizationSHA256[] = "{digest}";\n'
              f"static const char kCRDLocalizationJSON[] = {literal};\n")
    return header.encode("utf-8"), digest


def generate(directory: Path, output: Path) -> str:
    """Validate catalogs and write the header only when its bytes change."""
    data, digest = make_header(checked_catalogs(directory))
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_bytes() != data:
        output.write_bytes(data)
    return digest


# --- Command-line entry ---

def main() -> None:
    """Generate a native localization header from the selected catalog directory."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog-dir", type=Path, default=ROOT / "Sources/CRDSettingsCore/Resources/Localization")
    parser.add_argument("--output", type=Path, default=ROOT / "generated/Localization.h")
    args = parser.parse_args()
    digest = generate(args.catalog_dir, args.output)
    print(f"Generated {args.output.name}: {digest}")


if __name__ == "__main__":
    main()
