#!/usr/bin/env python3
"""Embed the shared Swift/native JSON contract without copying its defaults."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# --- Shared schema validation ---

def checked_schema(path: Path) -> dict:
    """Validate schema defaults, limits, choices and shape overrides before embedding them."""
    def unique(pairs):
        """Build a JSON object while rejecting duplicate keys."""
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f"duplicate JSON key: {key}")
            result[key] = value
        return result
    schema = json.loads(path.read_text(), object_pairs_hook=unique,
                        parse_constant=lambda value: (_ for _ in ()).throw(ValueError(value)))
    defaults, limits, choices, shapes = (schema[k] for k in ("defaults", "numericLimits", "choices", "shapes"))
    if not isinstance(defaults, dict) or not defaults:
        raise ValueError("defaults must be a nonempty object")
    for key, value in defaults.items():
        if type(value) not in (str, int, float, bool):
            raise ValueError(f"unsupported default type: {key}")
    for key, bounds in limits.items():
        if key not in defaults or type(defaults[key]) not in (int, float):
            raise ValueError(f"numeric limit has no numeric default: {key}")
        if len(bounds) != 2 or not bounds[0] <= defaults[key] <= bounds[1]:
            raise ValueError(f"invalid numeric limit/default: {key}")
    for key, values in choices.items():
        ids = [v["id"] for v in values]
        if len(set(ids)) != len(ids) or defaults[key] not in ids:
            raise ValueError(f"invalid choices/default: {key}")
    ids = [shape["id"] for shape in shapes]
    if len(set(ids)) != len(ids) or defaults["shape"] not in ids:
        raise ValueError("invalid shape default")
    for shape in shapes:
        for key, value in shape["values"].items():
            if key not in defaults or type(value) is not type(defaults[key]):
                raise ValueError(f"invalid shape override: {shape['id']}.{key}")
    return schema

# --- Native header generation ---

def main() -> None:
    """Embed deterministic schema JSON and its hash, preserving an unchanged output file."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schema", type=Path, default=ROOT / "Sources/CRDSettingsCore/Resources/SettingsSchema.json")
    parser.add_argument("--output", type=Path, default=ROOT / "generated/SettingsSchema.h")
    args = parser.parse_args()
    schema = checked_schema(args.schema)
    raw = json.dumps(schema, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    if ')CRDSCHEMA"' in raw:
        raise ValueError("reserved C++ raw-string delimiter in schema")
    sha = hashlib.sha256(raw.encode()).hexdigest()
    output = ("// Generated by scripts/generate_schema.py; edit SettingsSchema.json instead.\n"
              "#pragma once\n"
              f'static const char kCRDSettingsSchemaSHA256[] = "{sha}";\n'
              f'static const char kCRDSettingsSchemaJSON[] = R"CRDSCHEMA({raw})CRDSCHEMA";\n')
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.exists() or args.output.read_text() != output:
        args.output.write_text(output)
    print(f"Generated {args.output.name}: {sha}")

if __name__ == "__main__":
    main()
